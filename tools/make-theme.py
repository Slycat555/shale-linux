#!/usr/bin/env python3
"""Generates the Shale KDE color scheme (the default, a near-black #141414) from
Breeze Dark, and Shale Light from Breeze Light (found next to it).

Usage: make-theme.py /usr/share/color-schemes/BreezeDark.colors <repo>/system
Writes usr/share/color-schemes/ShaleDark.colors, ShaleLight.colors and
etc/xdg/kdeglobals. (The default scheme keeps the ShaleDark id the system defaults
point at; it used to be #1e1e1e, with a separate Shale Darker at #141414.)
"""
import os
import re
import sys

ACCENT = "53,132,228"         # #3584e4
ACCENT_DARK = "26,66,114"
# Greys for each variant: (base, window alt, view alt, button, tooltip).
VARIANTS = {
    "ShaleDark": ("Shale", "20,20,20", "28,28,28", "26,26,26", "35,35,35", "30,30,30"),  # #141414
}

src, out = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8").read()
text = re.sub(r"^# SPDX.*\n", "", text, flags=re.M)
text = text.replace("61,174,233", ACCENT).replace("161,169,177", "160,160,160")
text = text.replace("29,153,243", "88,160,240")


def make_scheme(scheme_id, name, bg, window_alt, view_alt, button, tooltip):
    groups = {
        # group: (BackgroundNormal, BackgroundAlternate)
        "Colors:Window": (bg, window_alt),
        "Colors:View": (bg, view_alt),
        "Colors:Button": (button, ACCENT_DARK),
        "Colors:Header": (bg, bg),
        "Colors:Header][Inactive": (bg, bg),
        "Colors:Tooltip": (tooltip, bg),
        "Colors:Complementary": (bg, ACCENT_DARK),
        "Colors:Selection": (ACCENT, ACCENT_DARK),
    }
    result = []
    for sec in re.split(r"^\[", text, flags=re.M):
        if not sec.strip():
            continue
        sname = sec.split("]\n", 1)[0] if "]\n" in sec else sec.split("]")[0]
        if sname in groups:
            bn, ba = groups[sname]
            sec = re.sub(r"^BackgroundNormal=.*$", f"BackgroundNormal={bn}", sec, flags=re.M)
            sec = re.sub(r"^BackgroundAlternate=.*$", f"BackgroundAlternate={ba}", sec, flags=re.M)
        if sname == "General":
            sec = f"General]\nColorScheme={scheme_id}\nName={name}\nshadeSortColumn=true\n\n"
        if sname == "WM":
            sec = (f"WM]\nactiveBackground={bg}\nactiveBlend=236,236,236\n"
                   f"activeForeground=236,236,236\ninactiveBackground={bg}\n"
                   "inactiveBlend=160,160,160\ninactiveForeground=160,160,160\n")
        result.append("[" + sec)
    return "".join(result).rstrip() + "\n"


for scheme_id, (name, bg, *rest) in VARIANTS.items():
    hex_bg = "#" + "".join(f"{int(c):02x}" for c in bg.split(","))
    with open(f"{out}/usr/share/color-schemes/{scheme_id}.colors", "w", encoding="utf-8") as f:
        f.write(f"# {name}: Breeze Dark with a neutral {hex_bg} palette.\n"
                "# Generated by tools/make-theme.py\n\n"
                + make_scheme(scheme_id, name, bg, *rest))


# Shale Light: Breeze Light's colours with Shale's accent and a flat title bar that
# matches the window, as in Shale Dark.
LIGHT_BG = "239,240,241"      # #eff0f1
LIGHT_ACCENT_TINT = "154,194,242"  # #3584e4 half-mixed with white
light = open(os.path.join(os.path.dirname(src), "BreezeLight.colors"), encoding="utf-8").read()
light = re.sub(r"^# SPDX.*\n", "", light, flags=re.M)
light = light.replace("61,174,233", ACCENT).replace("163,212,250", LIGHT_ACCENT_TINT)
light_result = []
for sec in re.split(r"^\[", light, flags=re.M):
    if not sec.strip():
        continue
    sname = sec.split("]\n", 1)[0] if "]\n" in sec else sec.split("]")[0]
    if sname in ("Colors:Header", "Colors:Header][Inactive"):
        sec = re.sub(r"^BackgroundNormal=.*$", f"BackgroundNormal={LIGHT_BG}", sec, flags=re.M)
        sec = re.sub(r"^BackgroundAlternate=.*$", f"BackgroundAlternate={LIGHT_BG}", sec, flags=re.M)
    if sname == "General":
        sec = "General]\nColorScheme=ShaleLight\nName=Shale Light\nshadeSortColumn=true\n\n"
    if sname == "WM":
        sec = (f"WM]\nactiveBackground={LIGHT_BG}\nactiveBlend=35,38,41\n"
               f"activeForeground=35,38,41\ninactiveBackground={LIGHT_BG}\n"
               "inactiveBlend=112,125,138\ninactiveForeground=112,125,138\n")
    light_result.append("[" + sec)
with open(f"{out}/usr/share/color-schemes/ShaleLight.colors", "w", encoding="utf-8") as f:
    f.write("# Shale Light: Breeze Light with Shale's accent and a flat title bar.\n"
            "# Generated by tools/make-theme.py\n\n" + "".join(light_result).rstrip() + "\n")

scheme = make_scheme("ShaleDark", *VARIANTS["ShaleDark"])

# System-wide defaults for every new user (live and installed).
kdeglobals = scheme.replace(
    "[KDE]\ncontrast=4\n",
    "[KDE]\ncontrast=4\nLookAndFeelPackage=org.shale.desktop\nwidgetStyle=Breeze\n")
kdeglobals += "\n[Icons]\nTheme=breeze-dark\n"
with open(f"{out}/etc/xdg/kdeglobals", "w", encoding="utf-8") as f:
    f.write("# Shale Linux defaults. Generated by tools/make-theme.py\n\n" + kdeglobals)
