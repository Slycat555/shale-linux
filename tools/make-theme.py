#!/usr/bin/env python3
"""Generates the Shale Dark KDE color scheme from Breeze Dark.

Usage: make-theme.py /usr/share/color-schemes/BreezeDark.colors <repo>/system
Writes usr/share/color-schemes/ShaleDark.colors and etc/xdg/kdeglobals.
"""
import re
import sys

ACCENT = "53,132,228"         # #3584e4
ACCENT_DARK = "26,66,114"
BG = "30,30,30"               # #1e1e1e

GROUPS = {
    # group: (BackgroundNormal, BackgroundAlternate)
    "Colors:Window": (BG, "38,38,38"),
    "Colors:View": (BG, "36,36,36"),
    "Colors:Button": ("45,45,45", ACCENT_DARK),
    "Colors:Header": (BG, BG),
    "Colors:Header][Inactive": (BG, BG),
    "Colors:Tooltip": ("40,40,40", BG),
    "Colors:Complementary": (BG, ACCENT_DARK),
    "Colors:Selection": (ACCENT, ACCENT_DARK),
}

src, out = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8").read()
text = re.sub(r"^# SPDX.*\n", "", text, flags=re.M)
text = text.replace("61,174,233", ACCENT).replace("161,169,177", "160,160,160")
text = text.replace("29,153,243", "88,160,240")

sections = re.split(r"^\[", text, flags=re.M)
result = []
for sec in sections:
    if not sec.strip():
        continue
    name = sec.split("]\n", 1)[0] if "]\n" in sec else sec.split("]")[0]
    if name in GROUPS:
        bn, ba = GROUPS[name]
        sec = re.sub(r"^BackgroundNormal=.*$", f"BackgroundNormal={bn}", sec, flags=re.M)
        sec = re.sub(r"^BackgroundAlternate=.*$", f"BackgroundAlternate={ba}", sec, flags=re.M)
    if name == "General":
        sec = "General]\nColorScheme=ShaleDark\nName=Shale Dark\nshadeSortColumn=true\n\n"
    if name == "WM":
        sec = ("WM]\nactiveBackground=30,30,30\nactiveBlend=236,236,236\n"
               "activeForeground=236,236,236\ninactiveBackground=30,30,30\n"
               "inactiveBlend=160,160,160\ninactiveForeground=160,160,160\n")
    result.append("[" + sec)
scheme = "".join(result).rstrip() + "\n"

with open(f"{out}/usr/share/color-schemes/ShaleDark.colors", "w", encoding="utf-8") as f:
    f.write("# Shale Dark: Breeze Dark with a neutral #1e1e1e palette.\n"
            "# Generated by tools/make-theme.py\n\n" + scheme)

# System-wide defaults for every new user (live and installed).
kdeglobals = scheme.replace(
    "[KDE]\ncontrast=4\n",
    "[KDE]\ncontrast=4\nLookAndFeelPackage=org.shale.desktop\nwidgetStyle=Breeze\n")
kdeglobals += "\n[Icons]\nTheme=breeze-dark\n"
with open(f"{out}/etc/xdg/kdeglobals", "w", encoding="utf-8") as f:
    f.write("# Shale Linux defaults. Generated by tools/make-theme.py\n\n" + kdeglobals)
